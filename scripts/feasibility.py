"""Narrow, disposable Matroska feasibility check; never accepts an input media file.

Fixture creation uses muxing/encoding. Application metadata writes only use mkvpropedit.
Requires Python 3.11+, FFmpeg, MKVToolNix and MediaInfo (CLI or Windows DLL).
"""
from __future__ import annotations

import argparse
import ctypes
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import time


def run(args: list[str | Path]) -> bytes:
    result = subprocess.run([str(arg) for arg in args], capture_output=True, timeout=60)
    if result.returncode != 0:
        raise RuntimeError(f"{Path(args[0]).name} exited {result.returncode}: "
                           f"{result.stderr.decode('utf-8', errors='replace')} "
                           f"{result.stdout.decode('utf-8', errors='replace')}")
    return result.stdout


def tool(name: str, directory: Path | None = None) -> Path:
    candidate = directory / f"{name}.exe" if directory else None
    if candidate and candidate.is_file():
        return candidate
    found = shutil.which(name)
    if not found:
        raise RuntimeError(f"Required utility not found: {name}")
    return Path(found)


def mediainfo(path: Path, dll_path: Path | None, cli: str | None) -> dict:
    if cli:
        return json.loads(run([cli, '--Output=JSON', path]))
    if os.name != 'nt' or dll_path is None:
        return json.loads(run([tool('mediainfo'), '--Output=JSON', path]))
    # Installed Windows MediaInfo is a GUI; the DLL exposes the same inspection engine.
    lib = ctypes.WinDLL(str(dll_path))
    lib.MediaInfo_New.restype = ctypes.c_void_p
    lib.MediaInfo_Option.argtypes = [ctypes.c_void_p, ctypes.c_wchar_p, ctypes.c_wchar_p]
    lib.MediaInfo_Option.restype = ctypes.c_wchar_p
    lib.MediaInfo_Open.argtypes = [ctypes.c_void_p, ctypes.c_wchar_p]
    lib.MediaInfo_Open.restype = ctypes.c_size_t
    lib.MediaInfo_Inform.argtypes = [ctypes.c_void_p, ctypes.c_size_t]
    lib.MediaInfo_Inform.restype = ctypes.c_wchar_p
    lib.MediaInfo_Delete.argtypes = [ctypes.c_void_p]
    handle = lib.MediaInfo_New()
    if not handle:
        raise RuntimeError('MediaInfo could not allocate an inspection handle')
    try:
        lib.MediaInfo_Option(handle, 'Output', 'JSON')
        if not lib.MediaInfo_Open(handle, str(path)):
            raise RuntimeError('MediaInfo could not open the generated fixture')
        return json.loads(lib.MediaInfo_Inform(handle, 0))
    finally:
        lib.MediaInfo_Delete(handle)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mkvtoolnix', type=Path)
    parser.add_argument('--mediainfo-cli')
    parser.add_argument('--mediainfo-dll', type=Path)
    parser.add_argument('--report', type=Path, default=Path('artifacts/feasibility.json'))
    parser.add_argument('--backend', type=Path, help='Also verify the production engine API on this disposable fixture')
    args = parser.parse_args()
    mkvmerge, mkvpropedit, mkvextract = [tool(name, args.mkvtoolnix) for name in ('mkvmerge', 'mkvpropedit', 'mkvextract')]
    ffmpeg = tool('ffmpeg')
    started = time.monotonic()
    with tempfile.TemporaryDirectory(prefix='tracksmith-fixture-') as folder:
        root = Path(folder)
        base = root / 'generated.mkv'
        fixture = root / 'Média [fixture] & spaces.mkv'
        subtitle = root / 'captions.srt'
        attachment = root / 'attachment.txt'
        chapters = root / 'chapters.txt'
        tags = root / 'tags.xml'
        subtitle.write_text('1\n00:00:00,000 --> 00:00:00,800\nTracksmith fixture\n', encoding='utf-8')
        attachment.write_text('Generated by Tracksmith. No external media.\n', encoding='utf-8')
        chapters.write_text('CHAPTER01=00:00:00.000\nCHAPTER01NAME=Opening\n', encoding='utf-8')
        tags.write_text('<Tags><Tag><Targets/><Simple><Name>COMMENT</Name><String>Preserve me</String></Simple></Tag></Tags>', encoding='utf-8')
        run([ffmpeg, '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=64x64:rate=5:duration=1',
             '-f', 'lavfi', '-i', 'sine=frequency=440:duration=1', '-map', '0:v', '-map', '1:a',
             '-c:v', 'libx264', '-preset', 'ultrafast', '-c:a', 'flac', base])
        run([mkvmerge, '-o', fixture, '--title', 'Original container', '--chapters', chapters,
             '--global-tags', tags, '--attachment-mime-type', 'text/plain', '--attach-file', attachment,
             base, '--language', '0:und', subtitle])

        def inspect() -> dict:
            data = json.loads(run([mkvmerge, '-J', fixture]))
            if not data.get('container', {}).get('recognized') or not data.get('container', {}).get('supported'):
                raise RuntimeError('Fixture identification failed')
            return data

        def stream_hashes(data: dict, prefix: str) -> dict[str, str]:
            result = {}
            for track in data['tracks']:
                out = root / f"{prefix}-{track['id']}.stream"
                run([mkvextract, fixture, 'tracks', f"{track['id']}:{out}"])
                result[str(track['properties']['uid'])] = hashlib.sha256(out.read_bytes()).hexdigest()
            return result

        before = inspect()
        hashes_before = stream_hashes(before, 'before')
        details = mediainfo(fixture, args.mediainfo_dll, args.mediainfo_cli)
        # Matroska track number is mkvmerge properties.number and MediaInfo ID.
        # This fixture verifies that correspondence; it does not establish a general mapping.
        mi_tracks = [track for track in details['media']['track'] if track['@type'] in ('Video', 'Audio', 'Text')]
        mapping = []
        for track in before['tracks']:
            number = str(track['properties']['number'])
            matches = [item for item in mi_tracks if str(item.get('ID')) == number]
            if len(matches) != 1:
                raise RuntimeError(f'No unambiguous MediaInfo track number match for {number}')
            expected_type = {'video': 'Video', 'audio': 'Audio', 'subtitles': 'Text'}[track['type']]
            if matches[0]['@type'] != expected_type:
                raise RuntimeError('Track type mismatch between inspection utilities')
            mapping.append({'mkvmerge_id': track['id'], 'number': number,
                            'uid': str(track['properties']['uid']), 'mediainfo_id': matches[0]['ID']})
        tags_before = run([mkvextract, fixture, 'tags'])
        chapters_before = run([mkvextract, fixture, 'chapters'])
        audio = next(track for track in before['tracks'] if track['type'] == 'audio')
        uid = str(audio['properties']['uid'])
        original_stat = fixture.stat()
        original_identity = (original_stat.st_dev, original_stat.st_ino)
        command = [mkvpropedit, fixture, '--edit', 'info', '--set', 'title=Tracksmith feasibility',
                   '--edit', f'track:={uid}', '--set', 'name=Audio — vérifié', '--set', 'language=en-GB',
                   '--set', 'flag-default=0']
        # Repeat the identical write once to check stable values and repeated-edit preservation.
        for _ in range(2):
            run(command)
            after = inspect()
            changed = next(track for track in after['tracks'] if str(track['properties']['uid']) == uid)
            props = changed['properties']
            assert after['container']['properties']['title'] == 'Tracksmith feasibility'
            assert props['track_name'] == 'Audio — vérifié'
            assert props['language'] == 'eng' and props['language_ietf'] == 'en-GB'
            assert props['default_track'] is False
            assert [(t['properties']['uid'], t['type']) for t in before['tracks']] == [(t['properties']['uid'], t['type']) for t in after['tracks']]
            for original, current in zip(before['tracks'], after['tracks'], strict=True):
                expected = json.loads(json.dumps(original))
                if str(expected['properties']['uid']) == uid:
                    expected['properties'].update(track_name='Audio — vérifié', language='eng', language_ietf='en-GB', default_track=False)
                assert expected == current, 'Unexpected track metadata change'
            assert stream_hashes(after, f'after-{_}') == hashes_before, 'Stream payload changed'
            assert run([mkvextract, fixture, 'tags']) == tags_before
            assert run([mkvextract, fixture, 'chapters']) == chapters_before
            assert before['attachments'] == after['attachments']
            out_attachment = root / f'attachment-{_}.txt'
            run([mkvextract, fixture, 'attachments', f"{after['attachments'][0]['id']}:{out_attachment}"])
            assert out_attachment.read_bytes() == attachment.read_bytes()
            new_stat = fixture.stat()
            assert (new_stat.st_dev, new_stat.st_ino) == original_identity, 'File identity changed'
        backend_result = None
        if args.backend:
            from engine_check import verify
            backend_result = verify(args.backend, fixture, root, mkvmerge, mkvextract, hashes_before)
        report = {
            'result': 'passed', 'fixture': 'generated 1s H.264 + FLAC + SRT; attachment, chapter, global tag',
            'mkvmerge_version': run([mkvmerge, '--version']).decode().strip(),
            'mkvpropedit_version': run([mkvpropedit, '--version']).decode().strip(),
            'track_mapping': mapping, 'stream_sha256': hashes_before,
            'verified': ['container title', 'track title', 'legacy + IETF language', 'default flag',
                         'track metadata preservation', 'track identity and order', 'extracted stream bytes',
                         'chapters', 'tags', 'attachment metadata and bytes', 'file identity', 'two consecutive writes'],
            'elapsed_seconds': round(time.monotonic() - started, 2),
            'backend': backend_result,
            'limits': ['One generated fixture; not broad container coverage.',
                       'No crash recovery, locked-file or full restoration guarantee.',
                       'MediaInfo mapping requires further validation on varied real-world structures.',
                       'Extraction hashing is a development check, not a production save operation.'],
        }
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
        print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
